describe("numberToGermanWord", () => {
  it.each(expectedPlain.map((word, index) => [index, word] as const))(
    "matches num-words-de for %i without indefinite article",
    (index, expected) => {
      expect(numberToGermanWord(index, { uppercase: false })).toBe(expected);
    },
  );

  it.each(expectedIndefiniteEine.map((word, index) => [index, word] as const))(
    "matches num-words-de for %i with indefinite_eine",
    (index, expected) => {
      expect(numberToGermanWord(index, { uppercase: false, indefinite_eine: true })).toBe(expected);
    },
  );

  it("capitalizes by default", () => {
    expect(numberToGermanWord(21)).toBe("Einundzwanzig");
  });

  it("uses ein in compounds", () => {
    expect(numberToGermanWord(21, { uppercase: false })).toBe("einundzwanzig");
    expect(numberToGermanWord(31, { uppercase: false })).toBe("einunddreißig");
  });

  it("uses eine for 1 with indefinite_eine", () => {
    expect(numberToGermanWord(1, { uppercase: false, indefinite_eine: true })).toBe("eine");
    expect(numberToGermanWord(1, { uppercase: false })).toBe("eins");
  });

  it("falls back to digits above 99", () => {
    expect(numberToGermanWord(100)).toBe("100");
    expect(numberToGermanWord(150, { uppercase: false })).toBe("150");
  });

  it("falls back for negatives and non-integers", () => {
    expect(numberToGermanWord(-1)).toBe("-1");
    expect(numberToGermanWord(1.5)).toBe("1.5");
    expect(numberToGermanWord(Number.NaN)).toBe("NaN");
  });
});
